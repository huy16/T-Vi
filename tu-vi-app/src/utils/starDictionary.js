export const getStarMeaning = (starName) => {
  if (!starName) return null;
  // Xử lý trường hợp tên sao có độ sáng (ví dụ: "Thiên Lương (M)")
  const cleanName = starName.split(' (')[0].trim();
  return STAR_DICTIONARY[cleanName] || null;
};
