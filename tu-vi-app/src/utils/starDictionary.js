/**
 * Trả về lời giải từ Cẩm Nang cho 1 danh sách tên sao.
 */
export const lookupStars = (starsArray) => {
  if (!starsArray || starsArray.length === 0) return [];
  return starsArray.map(starName => {
    // Lọc bỏ đuôi Độ Sáng (M), (V), (Đ), (H) và các đuôi khác để tra từ điển
    const cleanName = starName.replace(/\s\([MVĐH]\)$/, '').replace(/\s\([A-Z]\)$/, ''); 
    return {
      name: starName,
      meaning: STAR_DICTIONARY[cleanName] || "N/A"
    };
  });
};
